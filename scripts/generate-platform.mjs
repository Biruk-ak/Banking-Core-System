write('packages/domain-core/src/money.ts', lines(
  `/** Money value object — Banking Core System */`,
  `export type CurrencyCode = 'USD' | 'EUR' | 'GBP' | 'ETB' | 'AED' | 'JPY' | 'CHF' | 'CAD' | 'AUD' | 'CNY';`,
  ``,
  `export class Money {`,
  `  private constructor(`,
  `    public readonly amountMinor: bigint,`,
  `    public readonly currency: CurrencyCode,`,
  `  ) {`,
  `    if (!Number.isFinite(Number(amountMinor))) {`,
  `      throw new Error('Invalid money amount');`,
  `    }`,
  `  }`,
  ``,
  `  static of(amount: number | string | bigint, currency: CurrencyCode): Money {`,
  `    const n = typeof amount === 'bigint' ? amount : BigInt(Math.round(Number(amount) * 100));`,
  `    return new Money(n, currency);`,
  `  }`,
  ``,
  `  static zero(currency: CurrencyCode): Money {`,
  `    return new Money(0n, currency);`,
  `  }`,
  ``,
  `  add(other: Money): Money {`,
  `    this.assertSameCurrency(other);`,
  `    return new Money(this.amountMinor + other.amountMinor, this.currency);`,
  `  }`,
  ``,
  `  subtract(other: Money): Money {`,
  `    this.assertSameCurrency(other);`,
  `    return new Money(this.amountMinor - other.amountMinor, this.currency);`,
  `  }`,
  ``,
  `  multiply(factor: number): Money {`,
  `    const result = BigInt(Math.round(Number(this.amountMinor) * factor));`,
  `    return new Money(result, this.currency);`,
  `  }`,
  ``,
  `  isPositive(): boolean { return this.amountMinor > 0n; }`,
  `  isNegative(): boolean { return this.amountMinor < 0n; }`,
  `  isZero(): boolean { return this.amountMinor === 0n; }`,
  `  greaterThan(other: Money): boolean {`,
  `    this.assertSameCurrency(other);`,
  `    return this.amountMinor > other.amountMinor;`,
  `  }`,
  `  lessThan(other: Money): boolean {`,
  `    this.assertSameCurrency(other);`,
  `    return this.amountMinor < other.amountMinor;`,
  `  }`,
  `  equals(other: Money): boolean {`,
  `    return this.currency === other.currency && this.amountMinor === other.amountMinor;`,
  `  }`,
  `  toMajorUnits(): number { return Number(this.amountMinor) / 100; }`,
  `  format(locale = 'en-US'): string {`,
  `    return new Intl.NumberFormat(locale, { style: 'currency', currency: this.currency }).format(this.toMajorUnits());`,
  `  }`,
  `  private assertSameCurrency(other: Money): void {`,
  `    if (this.currency !== other.currency) {`,
  `      throw new Error(\`Currency mismatch: \${this.currency} vs \${other.currency}\`);`,
  `    }`,
  `  }`,
  `}`,
));

write('packages/domain-core/src/entity.ts', lines(
  `export abstract class Entity<TId extends string = string> {`,
  `  protected constructor(public readonly id: TId) {}`,
  `  equals(other: Entity<TId>): boolean { return this.id === other.id; }`,
  `}`,
  ``,
  `export abstract class AggregateRoot<TId extends string = string> extends Entity<TId> {`,
  `  private _domainEvents: DomainEvent[] = [];`,
  `  protected addDomainEvent(event: DomainEvent): void { this._domainEvents.push(event); }`,
  `  pullDomainEvents(): DomainEvent[] {`,
  `    const events = [...this._domainEvents];`,
  `    this._domainEvents = [];`,
  `    return events;`,
  `  }`,
  `}`,
  ``,
  `export interface DomainEvent {`,
  `  readonly eventId: string;`,
  `  readonly aggregateId: string;`,
  `  readonly eventType: string;`,
  `  readonly occurredAt: Date;`,
  `  readonly payload: Record<string, unknown>;`,
  `}`,
  ``,
  `export function createEvent(`,
  `  aggregateId: string,`,
  `  eventType: string,`,
  `  payload: Record<string, unknown>,`,
  `): DomainEvent {`,
  `  return {`,
  `    eventId: crypto.randomUUID(),`,
  `    aggregateId,`,
  `    eventType,`,
  `    occurredAt: new Date(),`,
  `    payload,`,
  `  };`,
  `}`,
));

write('packages/domain-core/src/result.ts', lines(
  `export type Result<T, E = Error> = Ok<T> | Err<E>;`,
  `export class Ok<T> {`,
  `  readonly ok = true as const;`,
  `  constructor(public readonly value: T) {}`,
  `  map<U>(fn: (v: T) => U): Result<U, never> { return new Ok(fn(this.value)); }`,
  `  flatMap<U, F>(fn: (v: T) => Result<U, F>): Result<U, F> { return fn(this.value); }`,
  `}`,
  `export class Err<E> {`,
  `  readonly ok = false as const;`,
  `  constructor(public readonly error: E) {}`,
  `  map<U>(_fn: (v: never) => U): Result<U, E> { return this as unknown as Result<U, E>; }`,
  `  flatMap<U, F>(_fn: (v: never) => Result<U, F>): Result<U, E | F> { return this as unknown as Result<U, E | F>; }`,
  `}`,
  `export const ok = <T>(value: T) => new Ok(value);`,
  `export const err = <E>(error: E) => new Err(error);`,
));

